bots AS (
  SELECT id, 2 + floor(random() * 3)::int AS cnt FROM users WHERE is_bot = TRUE
),
slots AS (
  SELECT b.id AS uid, row_number() OVER (ORDER BY random()) AS rn
  FROM bots b, generate_series(1, 4) AS n WHERE n <= b.cnt
)
